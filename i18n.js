let languageBlocks = new Set();
function bindLanguageBlock(container) {
    // Only call on freshly rendered system controls. Never on free-form content.
    for (const block of languageBlocks) if (!block.isConnected) languageBlocks.delete(block);
    const bindings = [], dictionary = {...interfaceEnglish,...controlEnglish};
    const reverse = Object.fromEntries(Object.entries(dictionary).map(([id,en])=>[en,id]));
    const pair = value => {
        const key = value.replace(/\s+/g,' ').trim();
        const id = currentLang === 'id' ? key : reverse[key];
        return dictionary[id] ? {id,en:dictionary[id]} : null;
    };
    const walker = document.createTreeWalker(container,NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        if (node.parentElement.closest('textarea,script,style')) continue;
        const labels = pair(node.textContent);
        if (labels) bindings.push({node,...labels});
    }
    container.querySelectorAll('[placeholder],[aria-label]').forEach(el=>{
        for (const attribute of ['placeholder','aria-label']) {
            const value = el.getAttribute(attribute), labels = value && pair(value);
            if (labels) bindings.push({el,attribute,...labels});
        }
    });
    container.languageBindings = bindings;
    languageBlocks.add(container);
}
function applyLanguageBlocks() {
    for (const container of languageBlocks) {
        if (!container.isConnected) { languageBlocks.delete(container); continue; }
        for (const binding of container.languageBindings) {
            if (binding.node?.isConnected) binding.node.textContent = binding[currentLang];
            if (binding.el?.isConnected) binding.el.setAttribute(binding.attribute,binding[currentLang]);
        }
    }
}
function localizedSystemNote(source) {
    const safe = sanitizeRichHtml(source);
    if (currentLang !== 'en') return safe;
    const doc = new DOMParser().parseFromString(safe.replace(/<br\s*\/?\s*>/gi,'\n'),'text/html');
    const text = doc.body.textContent;
    const revision = text.match(/^Berkas yang perlu diperbaiki:\n([\s\S]*?)\n\nInstruksi:\n([\s\S]*)$/);
    if (revision) return escapeHtml('Files needing corrections:\n' + revision[1].split('\n').map(line => line.startsWith('- ') ? '- ' + systemText(line.slice(2)) : line).join('\n') + '\n\nInstructions:\n' + revision[2]);
    const assignment = text.match(/^Pengajuan disetujui\. Dosen Pembimbing: (.+)\. Silakan hubungi dosen untuk tahapan bimbingan berikutnya\.$/);
    if (assignment) return escapeHtml('Request approved. Supervisor: ' + assignment[1] + '. Contact your supervisor for the next supervision stage.');
    if (text === 'Berkas telah disetujui dan terverifikasi.') return escapeHtml(systemText(text));
    return safe;
}
