function systemText(value) {
    const text = String(value ?? '');
    if (currentLang !== 'en') return text;
    const key = text.replace(/\s+/g, ' ').trim();
    if (interfaceEnglish[key]) return interfaceEnglish[key];
    const mismatch = key.match(/^Isi berkas tidak sesuai format (\.[a-z]+)\. Pilih dokumen asli; mengganti nama ekstensi tidak mengubah format\.$/);
    if (mismatch) return `The file contents do not match the ${mismatch[1]} format. Select the original document; renaming its extension does not convert it.`;
    const archive = key.match(/^Struktur (ZIP|DOCX) tidak terbaca atau belum lengkap\. Buat ulang berkas sebelum mengirim\.$/);
    if (archive) return `The ${archive[1]} structure is unreadable or incomplete. Recreate the file before submitting.`;
    return text;
}
function contentText(value, english) {
    const original = String(value ?? '');
    return currentLang === 'en' ? String(english || contentEnglish[original] || original) : original;
}
function documentText(value) {
    // Older outline uploads used "Proposal" as a document label. In a file list
    // this means the draft, while the service of that name is a proposal seminar.
    return currentLang === 'en' && value === 'Proposal' ? 'Proposal draft' : systemText(value);
}
function displayChecklistData(type) {
    return getChecklistData(type).map(group => ({...group, title:contentText(group.title,group.titleEn), items:(group.items || []).map(item => ({...item,text:contentText(item.text,item.textEn),sub:type === 'template_berkas' ? item.sub : contentText(item.sub,item.subEn)}))}));
}

// Bind only original page text, before any student/admin content is rendered.
// No observer walks conversations, names, titles, uploaded filenames or announcements.
let staticLanguageBindings = [];
function initInterfaceLanguage() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        if (node.parentElement.closest('script,style,svg,.lang')) continue;
        const key = node.textContent.replace(/\s+/g,' ').trim();
        if (interfaceEnglish[key]) {
            const parent = node.parentElement;
            if (['BUTTON','OPTION'].includes(parent.tagName) && !parent.childElementCount) {
                parent.classList.add('lang'); parent.dataset.id = key; parent.dataset.en = interfaceEnglish[key];
            } else staticLanguageBindings.push({node,id:node.textContent,en:interfaceEnglish[key]});
        }
    }
    document.querySelectorAll('[placeholder],[aria-label],[title]').forEach(el => {
        ['placeholder','aria-label','title'].forEach(attribute => {
            const value = el.getAttribute(attribute);
            if (interfaceEnglish[value]) staticLanguageBindings.push({el,attribute,id:value,en:interfaceEnglish[value]});
        });
    });
    applyStaticLanguage();
}
function applyStaticLanguage() {
    document.documentElement.lang = currentLang;
    document.title = uxText('IPCOS UMY — Portal Akademik', 'IPCOS UMY — Academic Portal');
    staticLanguageBindings.forEach(binding => {
        if (binding.node?.isConnected) binding.node.textContent = binding[currentLang];
        if (binding.el?.isConnected) binding.el.setAttribute(binding.attribute,binding[currentLang]);
    });
    const loginButton = document.getElementById('login-language-toggle');
    loginButton.textContent = currentLang === 'id' ? 'ID' : 'EN';
    loginButton.setAttribute('aria-label',uxText('Bahasa: Indonesia. Ganti ke English','Language: English. Switch to Indonesian'));
    loginButton.title = uxText('Ganti ke English','Switch to Indonesian');
    document.getElementById('lang-btn').textContent = uxText('English','Bahasa Indonesia');
}

function localizedDetailHtml(source) {
    const doc = new DOMParser().parseFromString(sanitizeRichHtml(source),'text/html');
    // Only the known field headings written by the submission code are translated.
    doc.querySelectorAll('b,strong').forEach(el => {
        const labels = {'Judul:':'Title:','Dosen Lama:':'Current supervisor:','Dosen Baru:':'Proposed supervisor:','Alasan:':'Reason:'};
        if (currentLang === 'en' && labels[el.textContent.trim()]) el.textContent = labels[el.textContent.trim()];
    });
    return doc.body.innerHTML;
}

